// Records harness scenarios from real replayed tracker states (mocked vision,
// zero provider calls). Run from prototypes/json_stream_site after a build:
//   node ../floating_guidance/scripts/make-fixtures.mjs
import {readFile,writeFile} from 'node:fs/promises';
import {replayLab} from '../../json_stream_site/scripts/replay-lab.mjs';
import {projectSnapshot,acceptedFrom,FG_SCHEMA} from '../../json_stream_site/assets/floating-guidance.js';

const data=new URL('../../json_stream_site/data/',import.meta.url);
const policy=JSON.parse(await readFile(new URL('guided-policy.json',data),'utf8')),definition=JSON.parse(await readFile(new URL('experiment.json',data),'utf8'));
const states=[];await replayLab({onState:v=>states.push(v.state)});
let sequence=0;
const wrap=body=>({schema:FG_SCHEMA,type:'replace_snapshot',stream_id:'fixture-stream-0001',generation:1,sequence:++sequence,body});
const project=(state,options)=>wrap(projectSnapshot(state,{policy,definition,...options}));
const live=states.find(s=>s.runtime.candidate&&s.runtime.capture_active&&s.guidance.current_action?.settings?.length);
const accepted=acceptedFrom(live);
const tweak=(change)=>{const s=structuredClone(live);change(s);return s;};
const cross=states.find(s=>!s.guidance.next_action&&s.guidance.next_instruction&&s.status==='active');
const gain=policy.procedures['CP-DSB-06'],gi=gain.findIndex(a=>a.id==='CP-DSB-06/gain-settings');
const scenarios={
 fresh:project(live,{accepted,ageMs:2000}),
 waiting_first:project(tweak(s=>{s.runtime.candidate=null;}),{accepted:null}),
 earlier:project(live,{accepted,ageMs:32000}),
 reading:project(live,{accepted,ageMs:4000,reading:true}),
 provider_wait:project(tweak(s=>{s.runtime.analysis_status='waiting_for_provider';s.runtime.analysis_error='provider_http_400';}),{accepted,ageMs:41000,retryAfterMs:900000}),
 paused:project(tweak(s=>{s.status='paused';s.runtime.candidate=null;}),{accepted,ageMs:6000}),
 sharing_off:project(tweak(s=>{s.runtime.capture_active=false;}),{accepted,ageMs:25000}),
 blocked:project(live,{accepted,ageMs:3000,blockedReason:'Share the MATLAB tab where Kiki is shown, so Kiki can keep its windows out of the screen read.'}),
 cross_stage_next:project(cross,{accepted:acceptedFrom(cross),ageMs:3000}),
 gain_settings:project(tweak(s=>{s.queue.current_checkpoint_id='CP-DSB-06';s.guidance={...s.guidance,current_action:gain[gi],next_action:gain[gi+1],action_position:gi+1,procedure:gain};}),{accepted:null}),
 completed:project(tweak(s=>{s.status='completed';s.queue={...s.queue,done_checkpoint_ids:definition.checkpoints.map(c=>c.id),current_checkpoint_id:null,upcoming_checkpoint_ids:[]};s.runtime.candidate=null;}),{accepted:null}),
 long_content:project(tweak(s=>{s.guidance.current_action={...s.guidance.current_action,how:Array(8).fill('Bring the named block’s settings into view and keep every field readable while Kiki checks the value against the authored table.')};}),{accepted,ageMs:2000}),
};
await writeFile(new URL('../harness/snapshots.js',import.meta.url),'// Generated by scripts/make-fixtures.mjs from replayed tracker states. Synthetic vision; not real Simulink evidence.\nglobalThis.KIKI_FIXTURES='+JSON.stringify(scenarios,null,1)+';\n');
console.log(JSON.stringify({scenarios:Object.keys(scenarios).length,source_states:states.length}));
