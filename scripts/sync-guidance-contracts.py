"""Generate isolated Worker schema constants; does not build/deploy any Site."""
import argparse,json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
paths=['lab_observer_drawing.v1.schema.json','analysis_owned_guidance.v0_1.schema.json','screen_writing.schema.json']
value={name:json.loads((root/'contracts'/path).read_text()) for name,path in zip(('MODEL_SCHEMA','GUIDANCE_SCHEMA','DRAWING_SCHEMA'),paths)}
text='// Generated by scripts/sync-guidance-contracts.py; pinned local contracts.\n'+''.join('export const '+name+' = '+json.dumps(schema,separators=(',',':'))+';\n' for name,schema in value.items())
target=root/'prototypes/json_stream_site/worker/guidance-contracts.js'
args=argparse.ArgumentParser();args.add_argument('--check',action='store_true');options=args.parse_args()
if options.check:
 if target.read_text()!=text:raise SystemExit('guidance contract constants are out of sync')
 print('Isolated Worker contracts match pinned schemas')
else:target.write_text(text)
